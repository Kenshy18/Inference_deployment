SOURCE_ID = "sqlite-geometry-benchmark"


def _index_rows(payload: dict[str, Any]) -> dict[tuple[str, int], dict[str, Any]]:
    return {
        (row["algorithm"], int(row["target_interval"])): row for row in payload["rows"]
    }


def _source() -> dict[str, Any]:
    return {
        "id": SOURCE_ID,
        "label": (
            "Production / Superior Pareto SQLite geometry benchmark (2026-08-07); "
            "generated by benchmark_matrix.py"
        ),
        "path": "output/superior_pareto_20260807/frequency_comparison_v8/report/benchmark_source.sql",
    }


